-- Additional associations only. Built-in associatedPokemon entries stay in code.
create table public.deck_identification_rules (
  id bigint generated by default as identity primary key,
  card text not null check (
    length(card) <= 100 and card ~ '^[a-z0-9]+(-[a-z0-9]+)*$'
  ),
  second_card text check (
    second_card is null or (
      length(second_card) <= 100
      and second_card ~ '^[a-z0-9]+(-[a-z0-9]+)*$'
      and second_card <> card
    )
  ),
  archetype text not null check (
    archetype ~ '^[a-z0-9]+(-[a-z0-9]+)*(,[a-z0-9]+(-[a-z0-9]+)*)?$'
    and length(split_part(archetype, ',', 1)) <= 100
    and length(split_part(archetype, ',', 2)) <= 100
    and split_part(archetype, ',', 1) <> split_part(archetype, ',', 2)
  )
);

alter table public.deck_identification_rules enable row level security;

-- Override any inherited default grants: everyone can read, authenticated
-- accounts can attempt writes, and the admin policy below authorizes them.
revoke all on public.deck_identification_rules from anon, authenticated;
grant select on public.deck_identification_rules to anon, authenticated;
grant insert, update, delete on public.deck_identification_rules to authenticated;
revoke all on sequence public.deck_identification_rules_id_seq from anon, authenticated;
grant usage, select on sequence public.deck_identification_rules_id_seq to authenticated;

create policy deck_rules_read on public.deck_identification_rules
  for select using (true);

